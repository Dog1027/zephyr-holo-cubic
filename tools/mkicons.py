#!/usr/bin/env python3
"""Generate the Menu's app icon font (src/icons.c, include/icons.h) from an icon font file.

Usage: uv run python tools/mkicons.py FONT [--size 72] [--preview icons.png]

FONT is any Nerd Font "Propo" file (they bundle Material Design Icons, whose code points are
used below), e.g. ~/.local/share/fonts/UbuntuNerdFontPropo-Regular.ttf. To change or add an icon,
edit ICONS (names and code points: https://www.nerdfonts.com/cheat-sheet, the nf-md-* ones) and
run this again; --preview writes a picture of the result to check before flashing.
The output is an LVGL font (4 bit per pixel, uncompressed) holding only these glyphs.
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

# (C name, Material Design Icons name, code point)
ICONS = [
    ("CLOCK", "clock-outline", 0xF0150),
    ("FILES", "folder-open", 0xF0770),
    ("GALLERY", "image-multiple", 0xF02F9),
    ("LEVEL", "spirit-level", 0xF14F1),
    ("DICE", "dice-5", 0xF01CE),
    ("LIGHT", "lightbulb-on", 0xF06E8),
    ("TIMER", "timer-outline", 0xF051B),
    ("SYSTEM", "memory", 0xF035B),
    ("CAST", "cast", 0xF0118),
    ("AQUARIUM", "jellyfish", 0xF0F01),
    ("TEST", "flask", 0xF0093),
    ("DEFAULT", "file", 0xF0214),
]

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render(font, cp):
    """(4 bpp nibbles row by row, width, height, x offset, y offset above the baseline, advance)"""
    ch = chr(cp)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        raise SystemExit(f"U+{cp:X} is not in this font")
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    nibbles = [v >> 4 for v in img.tobytes()]
    return nibbles, w, h, x0, -y1, font.getlength(ch), img


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("font")
    p.add_argument("--size", type=int, default=72, help="font size in pixels (the glyphs are a bit smaller)")
    p.add_argument("--preview", help="also write a PNG with all icons")
    args = p.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    glyphs = sorted(((cp, cname, name) + render(font, cp) for cname, name, cp in ICONS), key=lambda g: g[0])
    ascent = max(g[7] + g[5] for g in glyphs)       # top of the tallest glyph above the baseline
    descent = max(0, max(-g[7] for g in glyphs))    # lowest glyph below the baseline
    first, last = glyphs[0][0], glyphs[-1][0]
    assert last - first < 0x10000, "code points too far apart for one sparse cmap"

    bitmap, dsc, index = [], [], 0
    for cp, cname, name, nibbles, w, h, ox, oy, adv, _ in glyphs:
        if len(nibbles) % 2:
            nibbles = nibbles + [0]
        data = [nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2)]
        lines = ["    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
        bitmap.append(f"    /* U+{cp:X} {name} */\n" + "\n".join(lines))
        dsc.append(f"    {{.bitmap_index = {index}, .adv_w = {round(adv * 16)}, .box_w = {w}, .box_h = {h}, "
                   f".ofs_x = {ox}, .ofs_y = {oy}}},")
        index += len(data)

    src = f"""/*
 * App icons for the Menu: {len(glyphs)} glyphs of Material Design Icons (Apache 2.0, pictogrammers.com),
 * {args.size} px, 4 bpp. Generated by tools/mkicons.py, do not edit: change ICONS there and run it again.
 */
#include <lvgl.h>
#include "icons.h"

static const uint8_t glyph_bitmap[] = {{
{chr(10).join(bitmap)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
    {{.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}}, /* id 0 is reserved */
{chr(10).join(dsc)}
}};

static const uint16_t unicode_list[] = {{
    {", ".join(f"0x{g[0] - first:04x}" for g in glyphs)},
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 0x{first:X}, .range_length = {last - first + 1}, .glyph_id_start = 1,
        .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(glyphs)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
    }},
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t font_icons = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
"""
    hdr = """#pragma once

#include <lvgl.h>

/*
 * App icons for the Menu (APP_FG_REGISTER's icon). They are glyphs of font_icons, not of the
 * text fonts: use LV_SYMBOL_* everywhere else. Generated by tools/mkicons.py.
 */
extern const lv_font_t font_icons;

"""
    width = max(len(c) for c, _, _ in ICONS)
    for cname, name, cp in ICONS:
        utf8 = "".join(f"\\x{b:02X}" for b in chr(cp).encode())
        hdr += f"#define ICON_{cname:{width}} \"{utf8}\"  // {name}\n"

    with open(os.path.join(TOP, "src", "icons.c"), "w") as f:
        f.write(src)
    with open(os.path.join(TOP, "include", "icons.h"), "w") as f:
        f.write(hdr)
    print(f"{len(glyphs)} icons, {index} bytes of bitmaps, line height {ascent + descent}")

    if args.preview:
        cell = 96
        sheet = Image.new("RGB", (cell * 5, cell * ((len(glyphs) + 4) // 5)), (11, 15, 23))
        for i, g in enumerate(sorted(glyphs, key=lambda g: [c for c, _, _ in ICONS].index(g[1]))):
            img = g[-1]
            x, y = (i % 5) * cell, (i // 5) * cell
            sheet.paste((255, 255, 255), (x + (cell - img.width) // 2, y + (cell - img.height) // 2), img)
        sheet.save(args.preview)


if __name__ == "__main__":
    main()
